export function Icon({
  name,
  className,
}: {
  name: IconName;
  // `| undefined` on purpose: the portal builds with exactOptionalPropertyTypes,
  // and callers pass conditional classes as `cond ? 'x' : undefined`.
  className?: string | undefined;
}): ReactElement {
  return (
    <svg
      className={className ? `icon ${className}` : 'icon'}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2.2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {PATHS[name]}
    </svg>
  );
}
